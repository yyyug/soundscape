# Apply all replacements
$updated = 0
foreach ($kv in $translations.GetEnumerator()) {
    $key = $kv.Key
    # Match the line: "key" = "anything";
    $pattern = '(?m)^("' + [regex]::Escape($key) + '"\s*=\s*)"([^"\\]|\\[\s\S])*"(\s*;)'
    $replacement = "`${1}`"$($kv.Value)`"`${3}"
    $new = [regex]::Replace($content, $pattern, $replacement)
    if ($new -ne $content) {
        $content = $new
        $updated++
    }
}

[System.IO.File]::WriteAllText((Resolve-Path $filePath).Path, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host "Done. Updated $updated / $($translations.Count) entries."
